"""Validate declared delivery attachments against their sealed revisions."""
from hashlib import sha256
import json
from pathlib import Path
from typing import Literal
from zipfile import ZIP_DEFLATED, ZipFile

from geopandas import clip
from pypdfium2 import PdfDocument
from guizhi.domain.diagnostics import Fault

from guizhi.infrastructure.documents import checked_office
from guizhi.infrastructure.operations.common import compatible, field, valid
from guizhi.infrastructure.operations.evidence import read_artifact
from guizhi.infrastructure.operations.report import publish_report
from guizhi.infrastructure.vector import digest


def check_attachments(ctx, required: list[Literal["pdf", "docx", "xlsx"]]):
    supplied = []
    names = set()
    for item, (file, ref) in zip(ctx.request.inputs, ctx.documents, strict=True):
        ctx.check()
        name = Path(item.file).name
        if name.casefold() in names:
            raise ValueError("Attachment names must be unique")
        names.add(name.casefold())
        suffix = file.suffix[1:].lower()
        if suffix == "pdf":
            with PdfDocument(file) as pdf:
                if not len(pdf):
                    raise ValueError("PDF attachment has no pages")
        else:
            checked_office(file)
            with ZipFile(file) as office:
                entry = "word/document.xml" if suffix == "docx" else "xl/workbook.xml"
                if entry not in office.namelist() or office.testzip() is not None:
                    raise ValueError("Office attachment content does not match its format")
        supplied.append({"name": name, "format": suffix, "sha256": ref["sha256"]})
    missing = sorted(set(required) - {item["format"] for item in supplied})
    if missing:
        raise Fault("data", "missing_required_attachments", f"Missing required attachments: {', '.join(missing)}",
                    required_formats=missing)
    ctx.json("attachments.json", {"attachments": supplied}, "attachments")
    return {"statistics": {"attachment_count": len(supplied)}}


def clip_vector(ctx, fields: list[str]):
    source, area = ctx.frames
    compatible(ctx.frames)
    valid(source)
    valid(area, polygon=True)
    if not len(area) or area.geometry.is_empty.any() or len(set(fields)) != len(fields):
        raise ValueError("Shared delivery requires a nonempty scope and unique authorized fields")
    for name in fields:
        field(source, name)
    result = clip(source[[*fields, source.geometry.name]], area, keep_geom_type=True)
    ctx.publish(result, geometry_type=ctx.info[0]["geometry_type"] if result.empty else None)
    return {"scope_revision": ctx.selection_hashes[1], "fields": fields}


def bundle(ctx, vector_run: str, raster_run: str, attachment_run: str):
    files = []
    scopes = set()
    for run, operation, name in ((vector_run, "delivery.clip_vector", "data/矢量.gpkg"),
                                 (raster_run, "raster.clip", "data/栅格.tif")):
        record = ctx.workspace.read(run)
        if record["task"]["operation"] != operation:
            raise ValueError("Shared data must be generated by the matching scope clip")
        files.append((name, read_artifact(ctx.workspace, run, "export"), run))
        scopes.add(record["result"]["scope_revision"])
    if len(scopes) != 1:
        raise ValueError("Shared data does not have a common verified scope")
    attachment = ctx.workspace.read(attachment_run)
    if attachment["task"]["operation"] != "delivery.check_attachments":
        raise ValueError("Shared attachments must pass the attachment check")
    index = json.loads(read_artifact(ctx.workspace, attachment_run, "attachments").read_text(encoding="utf-8"))
    for number, item in enumerate(index["attachments"], 1):
        file = read_artifact(ctx.workspace, attachment_run, f"document-{number}")
        if digest(file) != item["sha256"] or Path(item["name"]).name != item["name"]:
            raise ValueError("Attachment evidence does not match the manifest")
        files.append(("attachments/" + item["name"], file, attachment_run))
    manifest = {"scope_revision": scopes.pop(), "files": [
        {"path": name, "sha256": digest(file), "run": run} for name, file, run in files]}
    package = ctx.path("shared-data.zip")
    with ZipFile(package, "w", ZIP_DEFLATED) as archive:
        for name, file, _ in files:
            ctx.check()
            archive.write(file, name)
        archive.writestr("manifest.json", json.dumps(manifest, ensure_ascii=False, indent=2))
    with ZipFile(package) as archive:
        if archive.namelist() != [item["path"] for item in manifest["files"]] + ["manifest.json"]:
            raise ValueError("Shared package contains unapproved files")
        for item in manifest["files"]:
            ctx.check()
            with archive.open(item["path"]) as stream:
                from hashlib import file_digest
                if file_digest(stream, sha256).hexdigest() != item["sha256"]:
                    raise ValueError("Shared package checksum mismatch")
    ctx.record("package", package)
    ctx.json("delivery.json", manifest, "manifest")
    publish_report(ctx, "共享交付清单", ("文件", "SHA-256"), [(item["path"], item["sha256"]) for item in manifest["files"]])
    return {"statistics": {"file_count": len(files)}}
